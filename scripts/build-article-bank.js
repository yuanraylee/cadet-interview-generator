#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { countWords, readLibrary } = require('./validate-articles.js');

const ROOT = path.resolve(__dirname, '..');
const LIBRARY_DIR = path.join(ROOT, 'data', 'article-library');
const OUTPUT_FILE = path.join(ROOT, 'data', 'articles.js');

function toWebsiteArticle(article) {
  const body = article.content.paragraphs.map((paragraph) => paragraph.en.trim()).join('\n\n');
  return {
    id: article.id,
    category: article.displayCategory,
    title: article.title,
    source: article.source.name,
    difficulty: article.difficulty,
    words: countWords(body),
    body
  };
}

function serializeJavaScript(articles) {
  const json = JSON.stringify(articles, null, 2)
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
  return `/* AUTO-GENERATED by scripts/build-article-bank.js. Do not edit directly. */
/* Add or update articles in data/article-library, then run the build script. */
window.OFFLINE_ARTICLES = ${json};
window.CADET_EXTRA_ARTICLES = [];
`;
}

function buildArticleBank() {
  const result = readLibrary(LIBRARY_DIR);
  if (result.errors.length) {
    const detail = result.errors.map((error) => `- ${error}`).join('\n');
    throw new Error(`Article validation failed:\n${detail}`);
  }
  const published = result.articles
    .filter((article) => article.status === 'published')
    .sort((a, b) => a.id.localeCompare(b.id, 'en'));
  if (!published.length) throw new Error('No published articles are available to build.');
  return { content: serializeJavaScript(published.map(toWebsiteArticle)), published };
}

function main() {
  try {
    const checkOnly = process.argv.includes('--check');
    const result = buildArticleBank();
    if (checkOnly) {
      const current = fs.existsSync(OUTPUT_FILE) ? fs.readFileSync(OUTPUT_FILE, 'utf8') : '';
      if (current !== result.content) {
        console.error('data/articles.js is out of date. Run: node scripts/build-article-bank.js');
        process.exitCode = 1;
        return;
      }
      console.log(`Article bank is current (${result.published.length} published article(s)).`);
      return;
    }
    fs.writeFileSync(OUTPUT_FILE, result.content, 'utf8');
    console.log(`Built data/articles.js with ${result.published.length} published article(s).`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

if (require.main === module) main();

module.exports = { buildArticleBank, serializeJavaScript, toWebsiteArticle };
